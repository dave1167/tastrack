const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const apiRoot = path.join(root, 'app', 'api');
const outputPath = path.join(root, 'app_docs', 'TENANT_LIFECYCLE_ENDPOINT_MATRIX.md');
const benign = new Set([
  'chat/directMarkRead.json', 'chat/markRead.json', 'chat/updateAvailability.json',
  'notifications/markRead.json', 'notifications/markAllRead.json'
]);

function walk(directory) {
  return fs.readdirSync(directory, {withFileTypes: true}).flatMap(entry => {
    const full = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(full) : entry.name.endsWith('.json') ? [full] : [];
  });
}

function flatten(value, out = []) {
  if (!value || typeof value !== 'object') return out;
  if (Array.isArray(value)) value.forEach(item => flatten(item, out));
  else {
    if (value.module || value.action) out.push(value);
    Object.values(value).forEach(item => flatten(item, out));
  }
  return out;
}

function inspect(file) {
  const relative = path.relative(apiRoot, file).replaceAll('\\', '/');
  const text = fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, '');
  let json;
  try { json = JSON.parse(text); } catch (error) { return {relative, parseError: error.message, mutating: false}; }
  const steps = flatten(json.exec);
  const method = String(json.settings?.options?.method || 'get').toLowerCase();
  const isSystem = relative.includes('/webhook/') || relative.endsWith('/webhook.json') || relative.startsWith('email/webhook/') || relative.includes('callback');
  const mutationText = text.match(/\b(INSERT\s+INTO|UPDATE\s+[`A-Za-z]|DELETE\s+FROM|TRUNCATE\s+TABLE|REPLACE\s+INTO)\b/i);
  const mutationActions = steps.filter(step => /^(insert|update|delete|upload|move|remove|send|transaction)$/i.test(String(step.action || '')));
  const mutating = method !== 'get' || Boolean(mutationText) || mutationActions.length > 0 || isSystem;
  if (!mutating) return {relative, mutating: false};
  const isPlatform = relative.startsWith('platform/');
  const isSecurity = relative.startsWith('login/') || relative.startsWith('security/') || relative === 'platform/login.json' || relative === 'platform/logout.json';
  let category = 'TENANT_BUSINESS_WRITE';
  if (isPlatform) category = 'PLATFORM_ADMIN_WRITE';
  if (isSystem) category = 'SYSTEM_TENANT_WRITE';
  if (isSecurity) category = 'SECURITY/AUTH';
  if (benign.has(relative)) category = 'TENANT_BENIGN_STATE_WRITE';
  const sql = steps.map(step => step.options?.sql?.query || '').filter(Boolean).join(' ');
  const tables = [...new Set([...sql.matchAll(/\b(?:INTO|UPDATE|FROM|JOIN)\s+`?(tbl_[A-Za-z0-9_]+)/gi)].map(match => match[1]))].sort();
  const trustedSystemProtection = relative === 'email/webhook/nylas.json' && fs.readFileSync(path.join(root, 'extensions', 'server_connect', 'modules', 'communicationEmail.js'), 'utf8').includes('lifecycle._decision(db,connection.tenantId)');
  const protectedLifecycle = text.includes('tenantLifecycle') || text.includes('lifecycleStatus') || text.includes('TENANT_READ_ONLY') || trustedSystemProtection;
  const tenantValidation = text.includes('$_SESSION.TENANT_ID') || (isSystem && /tenantId/i.test(text));
  const permission = Boolean(json.settings?.options?.restrict?.provider) && (/permission|role|isPlatformAdmin|owner-admin/i.test(text) || isPlatform);
  const origin = isPlatform ? 'platform-admin' : isSystem ? 'system/integration' : 'user';
  const requiredRule = category === 'TENANT_BUSINESS_WRITE' ? 'requireWrite(session tenant)' : category === 'SYSTEM_TENANT_WRITE' ? 'requireWrite(resolved trusted tenant)' : category === 'TENANT_BENIGN_STATE_WRITE' ? 'allow while tenant readable' : category === 'PLATFORM_ADMIN_WRITE' ? 'platform-admin override' : 'existing authentication policy';
  const action = category === 'TENANT_BUSINESS_WRITE' || category === 'SYSTEM_TENANT_WRITE' ? (protectedLifecycle ? 'protected' : 'pending protection') : category === 'TENANT_BENIGN_STATE_WRITE' ? 'explicit benign exemption' : 'existing authority retained';
  return {relative, mutating, category, tables: tables.join(', ') || 'indirect/configuration', tenantValidation, permission, protectedLifecycle, requiredRule, origin, action};
}

const records = walk(apiRoot).map(inspect).filter(record => record.mutating).sort((a, b) => a.relative.localeCompare(b.relative));
const counts = records.reduce((out, record) => { out[record.category] = (out[record.category] || 0) + 1; return out; }, {});
const unresolved = records.filter(record => ['TENANT_BUSINESS_WRITE','SYSTEM_TENANT_WRITE'].includes(record.category) && !record.protectedLifecycle).length;
const lines = [
  '# Tenant lifecycle endpoint matrix', '',
  'Generated by `scripts/h2-lifecycle-inventory.js`. This is the maintained H2 classification of every detected mutating Server Connect action.', '',
  `- Total mutating actions: ${records.length}`,
  ...Object.entries(counts).sort().map(([key, value]) => `- ${key}: ${value}`),
  `- Unresolved substantive/system actions: ${unresolved}`, '',
  '| Endpoint | Area/category | Tenant-owned data | Tenant validation | Permission validation | Lifecycle protection | Required rule | Origin | H2 action |',
  '|---|---|---|---:|---:|---:|---|---|---|',
  ...records.map(record => `| \`${record.relative}\` | ${record.category} | ${record.tables.replaceAll('|','\\|')} | ${record.tenantValidation ? 'yes' : 'no'} | ${record.permission ? 'yes' : 'inspect existing'} | ${record.protectedLifecycle ? 'yes' : 'no'} | ${record.requiredRule} | ${record.origin} | ${record.action} |`), '',
  '## Benign-state decisions', '',
  '- Notification read state, chat read state and personal availability are permitted while a tenant remains readable. They do not create or alter substantive workflow data.',
  '- Session/login/logout writes remain governed by authentication and access policy, not business-write policy.',
  '- Platform administration is exempt from target-tenant lifecycle blocking but continues to require an active platform administrator.', '',
  '## System-write policy', '',
  'Webhook and integration actions must derive the tenant from a trusted connection/grant/event record, then call the same central lifecycle decision with that resolved tenant before creating tenant business data.'
];
if (process.argv.includes('--write')) fs.writeFileSync(outputPath, lines.join('\n') + '\n');
process.stdout.write(JSON.stringify({total: records.length, counts, unresolved, outputPath}, null, 2));
